import Foundation
import PackagePlugin

/// Generates `HelperBuildInfo.swift` (`version` = VERSION + "+" + short git hash).
/// VERSION is read here, not by the shell command (reading it from the shell
/// command yielded an empty string under the build sandbox).
/// The hash is read straight from the git files (HEAD, the ref, packed-refs)
/// because the plugin sandbox may not be able to run `git`; falls back to
/// `unknown` when nothing resolves.
@main
struct HelperBuildInfoPlugin: BuildToolPlugin {
    func createBuildCommands(context: PluginContext, target: Target) throws -> [Command] {
        let root = context.package.directoryURL
        let versionFile = root.appending(path: "VERSION")
        let out = context.pluginWorkDirectoryURL.appending(path: "HelperBuildInfo.swift")

        var inputs = [versionFile]
        let version = Self.read(versionFile) ?? "0.0.0"
        let hash = Self.resolveHash(root: root, watching: &inputs)

        let script = """
        set -e
        v="$1"
        printf '// Generated by HelperBuildInfo. Do not edit.\\npublic enum HelperBuildInfo {\\n    public static let version = "%s+%s"\\n}\\n' "$v" "$2" > "$3"
        """
        return [
            .buildCommand(
                displayName: "Generate HelperBuildInfo",
                executable: URL(filePath: "/bin/sh"),
                arguments: ["-c", script, "sh", version, hash,
                            out.path(percentEncoded: false)],
                inputFiles: inputs,
                outputFiles: [out]
            )
        ]
    }

    private static func read(_ url: URL) -> String? {
        (try? String(contentsOf: url, encoding: .utf8))?.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private static func isHash(_ s: String) -> Bool {
        s.count >= 7 && s.allSatisfy { $0.isHexDigit && !$0.isUppercase }
    }

    static func resolveHash(root: URL, watching inputs: inout [URL]) -> String {
        let dotGit = root.appending(path: ".git")
        var gitDir = dotGit
        var isDir: ObjCBool = false
        if FileManager.default.fileExists(atPath: dotGit.path(percentEncoded: false), isDirectory: &isDir), !isDir.boolValue,
           let text = read(dotGit), text.hasPrefix("gitdir:") {
            // Worktree: `.git` is a file pointing at the real gitdir.
            let p = text.dropFirst("gitdir:".count).trimmingCharacters(in: .whitespaces)
            gitDir = p.hasPrefix("/") ? URL(filePath: p) : root.appending(path: p)
        }
        var commonDir = gitDir
        if let c = read(gitDir.appending(path: "commondir")) {
            commonDir = c.hasPrefix("/") ? URL(filePath: c) : gitDir.appending(path: c).standardized
        }
        let headFile = gitDir.appending(path: "HEAD")
        guard let head = read(headFile) else { return "unknown" }
        inputs.append(headFile)
        var full: String?
        if head.hasPrefix("ref:") {
            let ref = head.dropFirst("ref:".count).trimmingCharacters(in: .whitespaces)
            for dir in [gitDir, commonDir] {
                let refFile = dir.appending(path: ref)
                if let h = read(refFile), isHash(h) { inputs.append(refFile); full = h; break }
            }
            if full == nil, let packed = read(commonDir.appending(path: "packed-refs")) {
                for line in packed.split(separator: "\n") where line.hasSuffix(" " + ref) {
                    full = String(line.split(separator: " ")[0])
                }
            }
        } else if isHash(head) {
            full = head
        }
        guard let full, isHash(full) else { return "unknown" }
        return String(full.prefix(7))
    }
}
